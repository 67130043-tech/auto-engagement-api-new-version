def get_shop_info() -> dict:
    """
    คืนค่า dict ข้อมูลร้าน โดยให้ environment variable (ถ้ามีตั้งไว้) override ค่าใน
    SHOP_INFO ด้านบนเสมอ — เรียกทุกครั้งที่จะใช้ (ไม่ cache) เพื่อให้แก้ environment
    variable บน Render แล้วมีผลทันทีโดยไม่ต้อง restart service ใหม่เอง (บาง provider
    ก็ restart ให้อัตโนมัติอยู่แล้วเวลาแก้ env var แต่เผื่อกรณีที่ไม่ restart ด้วย)
    """
    info = dict(SHOP_INFO)
    for key in info:
        env_val = os.environ.get(f"SHOP_{key.upper()}")
        if env_val:
            info[key] = env_val
    return info
