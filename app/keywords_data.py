    if not any(t in _TASTE_QUESTION_SIGNAL for t in customer_tokens):
        return customer_tokens

    root_positions = [i for i, t in enumerate(customer_tokens) if t in _TASTE_ATTRIBUTE_ROOTS]
    if not root_positions:
        return customer_tokens

    has_customization_word = any(t in _TASTE_CUSTOMIZATION_SIGNAL for t in customer_tokens)
    question_positions = [i for i, t in enumerate(customer_tokens) if t in _TASTE_QUESTION_SIGNAL]

    result = list(customer_tokens)
    for ri in root_positions:
        near_question = any(abs(ri - qi) <= 3 for qi in question_positions)
        if near_question or has_customization_word:
            result[ri] = None
    return [t for t in result if t is not None]


