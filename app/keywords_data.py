"""
keywords_data.py
=================
สร้างชุดคำสำคัญ (keyword) ภาษาไทยสำหรับงาน sentiment/category classification
แบบ "คำราก x คำขยาย/คำนำหน้า" (combinatorial) แทนการพิมพ์คำนับพันคำด้วยมือ

ข้อดี:
- ได้คำครอบคลุมกว่า 2,000 คำ จากคำรากไม่ถึง 300 คำ
- แก้/เพิ่มคำทีหลังง่าย แค่เติมคำรากใหม่ 1 คำ ก็ได้ตัวแปรหลายสิบคำอัตโนมัติ
- ลดโอกาสพิมพ์ผิด/สะกดไม่ตรงกันระหว่างจุดต่างๆ ของโค้ด

วิธีใช้: import ตัวแปรจากไฟล์นี้ไปใช้ใน keyword_sentiment_override / keyword_category_override
"""

def combine(roots, suffixes=None, prefixes=None):
    """สร้างคำจากราก + ต่อท้าย/นำหน้า แล้วรวมกับคำรากเดิม (ไม่มีคำซ้ำเพราะเป็น set)"""
    out = set(roots)
    if suffixes:
        for r in roots:
            for s in suffixes:
                out.add(r + s)
    if prefixes:
        for r in roots:
            for p in prefixes:
                out.add(p + r)
    return out


