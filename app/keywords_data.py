def combine(roots, suffixes=None, prefixes=None):
    """สร้างคำจากราก + ต่อท้าย/นำหน้า แล้วรวมกับคำรากเดิม (ไม่มีคำซ้ำเพราะเป็น set)"""
    out = set(roots)
    if suffixes:
        for r in roots:
            for s in suffixes:
                out.add(r + s)
    if prefixes:
        for r in roots:
            for p in prefixes:
                out.add(p + r)
    return out


