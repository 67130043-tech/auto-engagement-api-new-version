def _expand(template: str, slots: dict) -> list:
    names = [n for n in slots if "{" + n + "}" in template]
    out = []
    for values in itertools.product(*(slots[n] for n in names)):
        kw = dict(zip(names, values))
        if "menu" in kw and "menu2" in kw and kw["menu"] == kw["menu2"]:
            continue
        out.append(template.format(**kw).replace("เลยเลย", "เลย"))
    return out


def generate(category: str, n: int, exclude: set, clean_fn, seed: int = 42) -> list:
    """คืน list ของ dict {clean_text, Category, source} สำหรับหมวด category จำนวนไม่เกิน n
    แถว โดยไม่ซ้ำกับข้อความใน exclude (ข้อความที่ clean แล้ว) เลือกแบบสุ่มด้วย seed คงที่
    และเฉลี่ยจำนวนต่อแม่แบบให้ใกล้เคียงกัน เพื่อไม่ให้แม่แบบใดแม่แบบหนึ่งครอบงำ"""
    if n <= 0:
        return []
    rng = random.Random(seed)
    rows = []
    for group, (cat, templates, slots) in TEMPLATE_GROUPS.items():
        if cat != category:
            continue
        pools = []
        for t in templates:
            pool = sorted({clean_fn(s) for s in _expand(t, slots)})
            rng.shuffle(pool)
            pools.append(pool)
        seen = set(exclude)
        # วนหยิบทีละแม่แบบ (round-robin) จนครบ n
        while len(rows) < n and any(pools):
            for pool in pools:
                while pool:
                    text = pool.pop()
                    if text and text not in seen:
                        seen.add(text)
                        rows.append({"clean_text": text, "Category": cat,
                                     "source": f"synthetic_{group}"})
                        break
                if len(rows) >= n:
                    break
    return rows
